import {describe, expect, it, vi} from "vitest"
import {asInstanceOf, Option, Terminable, UUID} from "@opendaw/lib-std"
import {Key, Shortcut, ShortcutDefinitions} from "@opendaw/lib-dom"
import {AudioUnitGroups, InstrumentFactories, ProjectSkeleton} from "@opendaw/studio-adapters"
import {AudioUnitBox} from "@opendaw/studio-boxes"
import type {Project} from "@opendaw/studio-core"
import {ShortcutStorage, ShortcutStore} from "@/service/ShortcutStorage"
import {GlobalShortcutsFactory} from "@/ui/shortcuts/GlobalShortcuts"
import {TrackGrouping} from "./TrackGrouping"

vi.hoisted(() => {
    if (Reflect.get(globalThis, "AudioWorkletNode") === undefined) {Reflect.set(globalThis, "AudioWorkletNode", class {})}
})
const sampleManager = () => ({
    getOrCreate: (uuid: UUID.Bytes) => ({
        get data() {return Option.None}, get peaks() {return Option.None}, get uuid() {return uuid},
        get state() {return {type: "idle"} as const}, invalidate() {}, subscribe: () => Terminable.Empty
    }), record: () => {}, invalidate: () => {}, remove: () => {}, register: () => Terminable.Empty
})
const setup = async () => {
    const {Project} = await import("@opendaw/studio-core")
    return Project.fromSkeleton({
        audioContext: undefined, audioWorklets: undefined, sampleManager: sampleManager(),
        soundfontManager: undefined, sampleService: undefined, soundfontService: undefined
    } as unknown as Parameters<typeof Project.fromSkeleton>[0],
    ProjectSkeleton.empty({createDefaultUser: true, createOutputMaximizer: false}))
}

const createUnits = (project: Project, count: number): ReadonlyArray<AudioUnitBox> =>
    project.editing.modify(() => Array.from({length: count}, () =>
        project.api.createAnyInstrument(InstrumentFactories.Neon).audioUnitBox)).unwrap()
const expectSelected = (project: Project, expected: ReadonlyArray<AudioUnitBox>): void => {
    const toKeys = (units: ReadonlyArray<AudioUnitBox>) => units.map(unit => UUID.toString(unit.address.uuid)).toSorted()
    expect(toKeys(project.audioUnitSelection.selected())).toEqual(toKeys(expected))
}

describe("track selection", () => {
    it("selects only the pressed track and adds or removes with toggle", async () => {
        const project = await setup()
        const [a, b, c, d] = createUnits(project, 4)
        expect(TrackGrouping.pressTrack(project, a, "replace")).toBeNull()
        expectSelected(project, [a])
        expect(TrackGrouping.pressTrack(project, c, "toggle")).toBeNull()
        expect(TrackGrouping.pressTrack(project, d, "toggle")).toBeNull()
        expectSelected(project, [a, c, d])
        expect(TrackGrouping.pressTrack(project, a, "toggle")).toBeNull()
        expectSelected(project, [c, d])
        expect(TrackGrouping.pressTrack(project, a, "toggle")).toBeNull()
        expectSelected(project, [a, c, d])
        expect(TrackGrouping.pressTrack(project, a, "toggle")).toBeNull()
        expectSelected(project, [c, d])
        expect(TrackGrouping.pressTrack(project, b, "replace")).toBeNull()
        expectSelected(project, [b])
        expect(TrackGrouping.pressTrack(project, b, "replace")).toBeNull()
        expectSelected(project, [b])
        project.terminate()
    })
    it("keeps a multi-selection on press for dragging and collapses it on release", async () => {
        const project = await setup()
        const [a, b, c] = createUnits(project, 3)
        TrackGrouping.selectTracks(project, [a, b, c])
        const release = TrackGrouping.pressTrack(project, b, "replace")
        expectSelected(project, [a, b, c])
        release?.()
        expectSelected(project, [b])
        project.terminate()
    })
    it("never selects the Output and clears the rest when it is pressed", async () => {
        const project = await setup()
        const [a, b] = createUnits(project, 2)
        TrackGrouping.selectTracks(project, [a, b, project.primaryAudioUnitBox])
        expectSelected(project, [a, b])
        TrackGrouping.pressTrack(project, project.primaryAudioUnitBox, "replace")
        expectSelected(project, [])
        TrackGrouping.pressTrack(project, a, "replace")
        TrackGrouping.pressTrack(project, project.primaryAudioUnitBox, "toggle")
        expectSelected(project, [a])
        project.terminate()
    })
    it("drops deleted tracks and keeps nested groups selectable", async () => {
        const project = await setup()
        const [a, b, c, d] = createUnits(project, 4)
        TrackGrouping.selectTracks(project, [b, c])
        project.editing.modify(() => project.api.deleteAudioUnit(c))
        expectSelected(project, [b])
        const group = project.editing.modify(() => project.grouping.create([a, b]).unwrap()).unwrap()
        project.editing.modify(() => group.groupCollapsed.setValue(true))
        TrackGrouping.pressTrack(project, group, "replace")
        TrackGrouping.pressTrack(project, d, "toggle")
        expectSelected(project, [group, d])
        TrackGrouping.pressTrack(project, d, "toggle")
        TrackGrouping.pressTrack(project, group, "toggle")
        expectSelected(project, [])
        project.terminate()
    })
    it("marks the line of the edited unit and its ancestors independent of the selection", async () => {
        const project = await setup()
        const [first, second, outside] = createUnits(project, 3)
        const parent = project.editing.modify(() => project.grouping.create([first, second]).unwrap()).unwrap()
        const nested = project.editing.modify(() => project.grouping.create([first]).unwrap()).unwrap()
        const units = [parent, nested, first, second, outside]
        const lines = () => units.map(unit => TrackGrouping.isTrackLineActive(project, unit))
        project.userEditingManager.audioUnit.edit(first.editing)
        TrackGrouping.selectTracks(project, [second])
        expect(lines()).toEqual([true, true, true, false, false])
        project.editing.modify(() => {nested.groupCollapsed.setValue(true); parent.groupCollapsed.setValue(true)})
        expect(lines()).toEqual([true, true, true, false, false])
        project.editing.modify(() => project.grouping.move([first]))
        expect(lines()).toEqual([false, false, true, false, false])
        project.userEditingManager.audioUnit.edit(nested.editing)
        expect(lines()).toEqual([true, true, false, false, false])
        project.userEditingManager.audioUnit.clear()
        expect(lines().some(active => active)).toBe(false)
        expectSelected(project, [second])
        project.terminate()
    })
    it("selects the visible range from the edited track with shift", async () => {
        const project = await setup()
        const [a, b, c, d] = createUnits(project, 4)
        const edit = (unit: AudioUnitBox) => project.userEditingManager.audioUnit.edit(unit.editing)
        TrackGrouping.pressTrack(project, b, "replace")
        edit(b)
        TrackGrouping.pressTrack(project, d, "range")
        expectSelected(project, [b, c, d])
        TrackGrouping.pressTrack(project, a, "range")
        expectSelected(project, [a, b])
        const group = project.editing.modify(() => project.grouping.create([c]).unwrap()).unwrap()
        project.editing.modify(() => group.groupCollapsed.setValue(true))
        TrackGrouping.pressTrack(project, d, "range")
        expectSelected(project, [b, group, d])
        project.userEditingManager.audioUnit.clear()
        TrackGrouping.pressTrack(project, a, "range")
        expectSelected(project, [a])
        project.terminate()
    })
    it("deselects tracks hidden by collapsing, nesting or moving into a collapsed group", async () => {
        const project = await setup()
        const deselecting = TrackGrouping.deselectHiddenTracks(project)
        const settle = () => Promise.resolve()
        const [a, b, c, d] = createUnits(project, 4)
        const group = project.editing.modify(() => project.grouping.create([a, b]).unwrap()).unwrap()
        TrackGrouping.selectTracks(project, [a, b, c])
        project.editing.modify(() => group.groupCollapsed.setValue(true))
        await settle()
        expectSelected(project, [c])
        project.editing.modify(() => group.groupCollapsed.setValue(false))
        await settle()
        expectSelected(project, [c])
        TrackGrouping.selectTracks(project, [a, b])
        const parent = project.editing.modify(() => project.grouping.create([group]).unwrap()).unwrap()
        project.editing.modify(() => parent.groupCollapsed.setValue(true))
        await settle()
        expectSelected(project, [])
        TrackGrouping.selectTracks(project, [c, d])
        project.editing.modify(() => project.grouping.move([c], parent))
        await settle()
        expectSelected(project, [d])
        expect(project.editing.canUndo()).toBe(true)
        deselecting.terminate()
        project.terminate()
    })
    it("undoes a collapse and the deselection it caused in one step", async () => {
        const project = await setup()
        const deselecting = TrackGrouping.deselectHiddenTracks(project)
        const settle = () => Promise.resolve()
        const [a, b, c] = createUnits(project, 3)
        const group = project.editing.modify(() => project.grouping.create([a, b]).unwrap()).unwrap()
        TrackGrouping.selectTracks(project, [a, c])
        project.editing.modify(() => c.volume.setValue(-3))
        project.editing.modify(() => group.groupCollapsed.setValue(true))
        await settle()
        expectSelected(project, [c])
        expect(project.editing.undo()).toBe(true)
        await settle()
        expect(group.groupCollapsed.getValue()).toBe(false)
        expectSelected(project, [a, c])
        expect(project.editing.redo()).toBe(true)
        await settle()
        expect(group.groupCollapsed.getValue()).toBe(true)
        expectSelected(project, [c])
        deselecting.terminate()
        project.terminate()
    })
    it("keeps the redo history when an undo hides a selected track", async () => {
        const project = await setup()
        const deselecting = TrackGrouping.deselectHiddenTracks(project)
        const settle = () => Promise.resolve()
        const [a, b] = createUnits(project, 2)
        const group = project.editing.modify(() => project.grouping.create([a, b]).unwrap()).unwrap()
        project.editing.modify(() => group.groupCollapsed.setValue(true))
        await settle()
        TrackGrouping.selectTracks(project, [a])
        project.editing.modify(() => b.volume.setValue(-3))
        project.editing.modify(() => group.groupCollapsed.setValue(false))
        await settle()
        expectSelected(project, [a])
        expect(project.editing.undo()).toBe(true)
        await settle()
        expect(project.editing.undo()).toBe(true)
        await settle()
        expect(project.editing.redo()).toBe(true)
        await settle()
        expect(project.editing.redo()).toBe(true)
        await settle()
        expect(project.editing.canRedo()).toBe(false)
        expect(group.groupCollapsed.getValue()).toBe(false)
        deselecting.terminate()
        project.terminate()
    })
})

describe("group and duplicate commands", () => {
    it("deletes every selected track and group subtree in one step when the pressed track is part of a multi-selection", async () => {
        const project = await setup()
        const [a, b, c, d] = createUnits(project, 4)
        const group = project.editing.modify(() => project.grouping.create([b, c]).unwrap()).unwrap()
        TrackGrouping.selectTracks(project, [a])
        expect(TrackGrouping.deleteSelectedTracks(project, a)).toBe(false)
        TrackGrouping.selectTracks(project, [a, group, c])
        expect(TrackGrouping.deleteSelectedTracks(project, d)).toBe(false)
        expect(TrackGrouping.deleteSelectedTracks(project, a)).toBe(true)
        expect([a, b, c, group].some(unit => unit.isAttached())).toBe(false)
        expect(d.isAttached()).toBe(true)
        project.editing.undo()
        expect([a, b, c, group].every(unit => project.boxGraph.findBox(unit.address.uuid).nonEmpty())).toBe(true)
        project.terminate()
    })
    it("groups the selection, selects the group and undoes both in one step", async () => {
        const project = await setup()
        const [a, b, c] = createUnits(project, 3)
        TrackGrouping.selectTracks(project, [a, b])
        TrackGrouping.groupSelectedTracks(project)
        const group = AudioUnitGroups.parent(a).unwrap()
        expectSelected(project, [group])
        expect(project.userEditingManager.audioUnit.isEditing(group.editing)).toBe(true)
        expect(project.editing.undo()).toBe(true)
        expect(AudioUnitGroups.parent(a).isEmpty()).toBe(true)
        expect(project.boxGraph.findBox(group.address.uuid).isEmpty()).toBe(true)
        expect(project.editing.redo()).toBe(true)
        expect(AudioUnitGroups.parent(a).nonEmpty()).toBe(true)
        expect(AudioUnitGroups.parent(c).isEmpty()).toBe(true)
        project.terminate()
    })
    it("duplicates the selection, selects the copies and undoes both in one step", async () => {
        const project = await setup()
        const [a, b] = createUnits(project, 2)
        TrackGrouping.selectTracks(project, [a, b])
        TrackGrouping.duplicateSelectedTracks(project)
        const copies = project.audioUnitSelection.selected()
        expect(copies).toHaveLength(2)
        expect(copies.some(unit => unit === a || unit === b)).toBe(false)
        expect(project.editing.undo()).toBe(true)
        expect(copies.every(unit => project.boxGraph.findBox(unit.address.uuid).isEmpty())).toBe(true)
        project.terminate()
    })
    it("does nothing without a selection", async () => {
        const project = await setup()
        const [a] = createUnits(project, 1)
        project.userEditingManager.audioUnit.edit(a.editing)
        const before = AudioUnitGroups.ordered(project.rootBox).length
        TrackGrouping.groupSelectedTracks(project)
        TrackGrouping.duplicateSelectedTracks(project)
        expect(AudioUnitGroups.ordered(project.rootBox)).toHaveLength(before)
        expect(AudioUnitGroups.parent(a).isEmpty()).toBe(true)
        project.terminate()
    })
})

describe("ungroup command", () => {
    it("ungroups selected nested groups together, selects promoted tracks and undoes in one step", async () => {
        const project = await setup()
        const [first, second] = project.editing.modify(() => [0, 1].map(() =>
            project.api.createAnyInstrument(InstrumentFactories.Neon).audioUnitBox)).unwrap()
        const outer = project.editing.modify(() => project.grouping.create([first, second]).unwrap()).unwrap()
        const inner = project.editing.modify(() => project.grouping.create([first]).unwrap()).unwrap()
        TrackGrouping.selectTracks(project, [outer, inner])
        TrackGrouping.ungroupSelectedTracks(project)
        expect(outer.isAttached()).toBe(false)
        expect(inner.isAttached()).toBe(false)
        expectSelected(project, [first, second])
        expect(AudioUnitGroups.parent(first).isEmpty()).toBe(true)
        expect(first.output.targetVertex.unwrap().box).toBe(project.primaryAudioBusBox)
        expect(project.editing.undo()).toBe(true)
        const restoredInner = asInstanceOf(project.boxGraph.findBox(inner.address.uuid).unwrap(), AudioUnitBox)
        expect(AudioUnitGroups.parent(first).unwrap().address.equals(inner.address)).toBe(true)
        expect(AudioUnitGroups.parent(restoredInner).unwrap().address.equals(outer.address)).toBe(true)
        expect(AudioUnitGroups.parent(second).unwrap().address.equals(outer.address)).toBe(true)
        expect(project.editing.redo()).toBe(true)
        expect(project.boxGraph.findBox(inner.address.uuid).isEmpty()).toBe(true)
        expect(project.boxGraph.findBox(outer.address.uuid).isEmpty()).toBe(true)
        expect(AudioUnitGroups.parent(first).isEmpty()).toBe(true)
        project.boxGraph.verifyPointers()
        project.terminate()
    })
    it("ungroups nothing without a selection and ignores the edited group", async () => {
        const project = await setup()
        const track = project.editing.modify(() => project.api.createAnyInstrument(InstrumentFactories.Neon).audioUnitBox).unwrap()
        TrackGrouping.selectTracks(project, [track])
        TrackGrouping.ungroupSelectedTracks(project)
        expect(track.isAttached()).toBe(true)
        const group = project.editing.modify(() => project.grouping.create([track]).unwrap()).unwrap()
        TrackGrouping.selectTracks(project, [])
        project.userEditingManager.audioUnit.edit(group.editing)
        TrackGrouping.ungroupSelectedTracks(project)
        expect(group.isAttached()).toBe(true)
        TrackGrouping.selectTracks(project, [group])
        TrackGrouping.ungroupSelectedTracks(project)
        expect(group.isAttached()).toBe(false)
        expectSelected(project, [track])
        project.terminate()
    })
    it("migrates saved group shortcuts through upstream custom-only shortcut storage", () => {
        const customGroup = Shortcut.of(Key.KeyG, {ctrl: true, alt: true})
        const customUngroup = Shortcut.of(Key.KeyU, {ctrl: true, shift: true})
        const values = new Map<string, string>([[ShortcutStorage.LegacyStorageKey, JSON.stringify({global: {
            "group-tracks": customGroup.toJSON(), "ungroup-tracks": customUngroup.toJSON(),
            "workspace-screen-piano": Shortcut.of(Key.Digit3, {shift: true}).toJSON()
        }})]])
        const storage: ShortcutStore = {
            getItem: key => values.get(key) ?? null,
            setItem: (key, value) => {values.set(key, value)},
            removeItem: key => {values.delete(key)}
        }
        const contexts = {global: {factory: GlobalShortcutsFactory, workingDefinition: ShortcutDefinitions.copy(GlobalShortcutsFactory)}}
        expect(ShortcutStorage.load(contexts, storage)).toBe(true)
        expect(contexts.global.workingDefinition["group-tracks"].shortcut.equals(customGroup)).toBe(true)
        expect(contexts.global.workingDefinition["ungroup-tracks"].shortcut.equals(customUngroup)).toBe(true)
        expect(contexts.global.workingDefinition["workspace-screen-piano"].shortcut
            .equals(GlobalShortcutsFactory["workspace-screen-piano"].shortcut)).toBe(true)
        expect(values.has(ShortcutStorage.LegacyStorageKey)).toBe(false)
        const stored = JSON.parse(values.get(ShortcutStorage.StorageKey) ?? "{}")
        expect(Object.keys(stored.global).sort()).toEqual(["group-tracks", "ungroup-tracks"])
        const restored = {global: {factory: GlobalShortcutsFactory, workingDefinition: ShortcutDefinitions.copy(GlobalShortcutsFactory)}}
        expect(ShortcutStorage.load(restored, storage)).toBe(true)
        expect(restored.global.workingDefinition["ungroup-tracks"].shortcut.equals(customUngroup)).toBe(true)
    })
    it("keeps old shortcut preferences and persists a remapped ungroup action independently", () => {
        const shortcuts = ShortcutDefinitions.copy(GlobalShortcutsFactory)
        const customGroup = Shortcut.of(Key.KeyG, {ctrl: true, alt: true})
        ShortcutDefinitions.fromJSON(shortcuts, {"group-tracks": customGroup.toJSON()})
        expect(shortcuts["group-tracks"].shortcut.equals(customGroup)).toBe(true)
        expect(shortcuts["ungroup-tracks"].shortcut.equals(Shortcut.of(Key.KeyG, {ctrl: true, shift: true}))).toBe(true)
        const customUngroup = Shortcut.of(Key.KeyU, {ctrl: true, shift: true})
        shortcuts["ungroup-tracks"].shortcut.overrideWith(customUngroup)
        const restored = ShortcutDefinitions.copy(GlobalShortcutsFactory)
        ShortcutDefinitions.fromJSON(restored, JSON.parse(JSON.stringify(ShortcutDefinitions.toJSON(shortcuts))))
        expect(restored["ungroup-tracks"].shortcut.equals(customUngroup)).toBe(true)
        expect(restored["group-tracks"].shortcut.equals(customGroup)).toBe(true)
    })
})
